const dictionaries = { en, de };
let language = 'en';

/** 'de*' gives German, everything else English. */
export function detectLanguage() {
  const preferred = (navigator.language || 'en').toLowerCase();
  return preferred.startsWith('de') ? 'de' : 'en';
}

export function getLanguage() {
  return language;
}

export function setLanguage(lang) {
  language = dictionaries[lang] ? lang : 'en';
  document.documentElement.lang = language;
  applyI18n();
}

export function t(key, params) {
  const text = dictionaries[language][key] ?? en[key] ?? key;
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in params ? params[name] : match));
}

/** Plural helper: uses key.one for 1 and key.other otherwise. {n} is available in the text. */
export function tn(key, n, params = {}) {
  return t(`${key}.${n === 1 ? 'one' : 'other'}`, { n, ...params });
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const attr of ['placeholder', 'title', 'aria-label']) {
    for (const el of root.querySelectorAll(`[data-i18n-${attr}]`)) el.setAttribute(attr, t(el.getAttribute(`data-i18n-${attr}`)));
  }
}
